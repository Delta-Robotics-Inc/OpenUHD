/**
 * RadioMaster RP1 V2 ExpressLRS 2.4GHz Nano Receiver (FCC / LBT) — datasheet-honest UHD part.
 *
 * Sources (see ./radiomaster-rp1-v2-elrs-2g4/sources.json):
 *   - src_manual:       RadioMaster RP1 Receiver User Manual (PDF) —
 *     https://cdn.shopify.com/s/files/1/0609/8324/7079/files/RP1_User_Manual.pdf?v=1722923320
 *   - src_product:      RadioMaster RP1 V2 product page —
 *     https://radiomasterrc.com/products/rp1-expresslrs-2-4ghz-nano-receiver
 *   - src_elrs_wiring:  ExpressLRS docs, Receiver Wiring —
 *     https://www.expresslrs.org/quick-start/receivers/wiring-up/
 *   - src_elrs_webui:   ExpressLRS docs, Web UI (UART baud) —
 *     https://www.expresslrs.org/quick-start/webui/
 *   - src_elrs_signal:  ExpressLRS docs, Signal Health (sensitivity limits) —
 *     https://www.expresslrs.org/info/signal-health/
 *   - src_elrs_targets / src_elrs_layout: ExpressLRS targets repo (rp1 target, Generic 2400 layout)
 *   - src_rdq:          RaceDayQuads listing (distributor, corroboration only)
 *
 * Modelling notes:
 *   - Hardware locked to RP1 V2 (the version RadioMaster currently sells; TCXO,
 *     rigid T antenna, top LED). FCC and LBT listings differ only in firmware
 *     regulatory domain, so one module covers both (usage_note).
 *   - Four solder pads are leaves: `vcc_5v` (PowerIn, 5 V), `gnd` (Ground),
 *     and `crsf_tx` / `crsf_rx` generated by the CRSF builder (device role,
 *     420000 baud = ExpressLRS default per src_elrs_webui). Pad labels follow
 *     the manual's top-view strip "RX TX 5V G"; the bottom silkscreen reads
 *     "(-) 5V TX RX", so the ground pad is labelled "G" (top) / "-" (bottom).
 *   - The FC side is a plain UART host; the receiver's TX goes to FC RX and
 *     its RX to FC TX (crossover), recorded as a usage_note on `crsf`.
 *   - The BOOT pad (short to GND while powering on, for firmware upgrade) is a
 *     service contact, not a system connection; it is described in a
 *     usage_note rather than modelled as a leaf.
 *   - Supply current and pad logic levels are not stated anywhere: no
 *     max_current or signal voltage parameter is set (data_gap traits).
 *   - Antenna: U.FL socket as an `rf` transceiver interface (`antenna_ufl`,
 *     network domain) with connectorTrait("u_fl"). The included 65 mm U.FL
 *     T antenna is not a separate module; it is noted on the interface.
 *     There is no dedicated antenna-connector protocol (vocabulary gap).
 *   - Mounting: no holes; the part is shrink-wrapped / taped / zip-tied, so
 *     there is no mechanical interface (usage_note + vocabulary gap). The
 *     verify "no mechanical interfaces" warning is expected for this reason.
 *   - Thermal: no source gives an operating temperature, so there is no
 *     thermal domain (data_gap). The verify "no thermal domain" warning is
 *     expected for this reason.
 *   - Conflicts are carried as source_discrepancy traits: RF chip
 *     (SX1281 vs SX1280 vs SX1276), pre-installed firmware (v3.0 vs v2.4),
 *     frequency range (2400-2483 MHz vs 2.404-2.479 GHz), telemetry power
 *     (10 mW vs 13 dBm layout setting), and weight basis (CN manual).
 *   - Sensitivity values are ExpressLRS generic 2.4 GHz per-rate limits, not
 *     RP1-specific measurements; they are labelled as such.
 */
