const crsfInterfaces = CRSF({
  id: "crsf",
  name: "CRSF (UART)",
  baudRate: CRSF_BAUD,
  rx: { pin: "RX", name: "RX" },
  tx: { pin: "TX", name: "TX" },
});

const PAD_FUNCTIONS: Record<string, { label: string; description: string }> = {
  crsf_tx: {
    label: "TX",
    description:
      "Receiver serial TX: sends CRSF control data received from the radio to the flight controller. Wire to FC RX of the same UART.",
  },
  crsf_rx: {
    label: "RX",
    description:
      "Receiver serial RX: accepts telemetry from the flight controller for the radio. Wire to FC TX of the same UART.",
  },
};

for (const iface of crsfInterfaces) {
  const fn = PAD_FUNCTIONS[iface.id];
  if (fn) {
    iface.traits = [
      ...(iface.traits ?? []),
      { type: "pin_functions", params: { ...fn, source: [SRC.manual, SRC.elrsWiring] } },
      {
        type: "data_gap",
        params: {
          field: "logic level",
          note: "No source states the TX/RX pad logic level or 5V tolerance.",
          source: SRC.manual,
        },
      },
    ];
  }
  if (iface.id === "crsf") {
    iface.traits = [
      ...(iface.traits ?? []),
      {
        type: "usage_note",
        params: {
          note:
            "Crossover to the FC UART: receiver TX -> FC RX, receiver RX -> FC TX (same UART number). Avoid FC UARTs with SBUS pull-downs on RX (can hold the receiver in bootloader). In Betaflight: Ports tab -> enable Serial RX on that UART; Configuration/Receiver -> Serial-based receiver, provider CRSF.",
          source: [SRC.elrsWiring, SRC.manual],
        },
      },
      {
        type: "usage_note",
        params: {
          note: "Leave UART baud at the default 420000; set 400000 only for KISS/KISS Ultra flight controllers.",
          source: SRC.elrsWebui,
        },
      },
    ];
  }
}

