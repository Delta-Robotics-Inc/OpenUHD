/**
 * SparkFun N20 Motor With Encoder and Cable (ROB-28633, one motor of the pair) — datasheet-honest UHD part.
 *
 * Sources (see ./sparkfun-rob-28633/sources.json):
 *   - src_datasheet: BJ-N20-12-1000 encoder motor specification (SparkFun) — https://cdn.sparkfun.com/assets/a/3/9/9/9/28633_datasheet_N20_Motor_With_Encoder_and_Cable_pair.pdf
 *   - src_product:   SparkFun ROB-28633 product page — https://www.sparkfun.com/n20-motor-with-encoder-and-cable-pair.html
 *   - src_protopart: ProtoPart sparkfun-rob-28633 definition (starting point only)
 *
 * Modelling notes:
 *   - Identity: ROB-28633 is sold as a PAIR. This part is one motor; place it
 *     twice for the pair. The datasheet is the vendor spec "BJ-N20-12-1000".
 *   - Six leaves, one per JST-SH (SH1.0-6P) contact, in cable order from the
 *     datasheet: 1 Blue GND, 2 Green Encoder A, 3 White Encoder B, 4 Yellow
 *     3.3V, 5 Black Motor -, 6 Red Motor +. Every contact interface refs the
 *     cable exit (the plug is at the end of the 100 mm cable).
 *   - `motor`: the brushed DC motor pair (Motor + / Motor -) as a composed
 *     `power` input, mirroring the l298n `dc_motor_output` pair (vocabulary
 *     gap: no brushed-motor builder). 3.7-12 V (datasheet). `max_current` 0.3 A
 *     is the rated-load current at 12 V; `burst_current` 0.7 A is the 12 V stall
 *     current (a driver must survive it).
 *   - `encoder`: the dual-Hall quadrature output (A/B square wave, 7 PPR at
 *     the motor, 882 counts per output revolution) as a composed `custom`
 *     interface (vocabulary gap: no quadrature type). VCC 3.3-5 V ("Encoder
 *     voltage 3.3/5V"; the pinout labels pin 4 "3.3V"). The output stage type
 *     is not stated (data_gap), so A/B are digital outputs with no drive rating.
 *   - `shaft`: Shaft (output) Φ3 mm D-shaft, 10 mm long.
 *   - No mounting holes are dimensioned in either source, so there is no
 *     BoltPattern (data_gap); N20 gearboxes are usually clamped.
 *   - Discrepancies (source_discrepancy traits): gear ratio 1:30 (datasheet
 *     table) vs 31.5:1 (SparkFun; consistent with 882 = 7 x 4 x 31.5), 31.5:1
 *     used; ProtoPart's 6 V nominal motor supply is not a manufacturer rating
 *     (SparkFun quotes 6 V figures for the XRP, the datasheet rates 12 V).
 *   - Thermal: no operating temperature in any source (justifies verify's
 *     coverage warning; data_gap trait).
 *   - Geometry: no manufacturer CAD; generated by
 *     library/cad/py/catalog/sparkfun-rob-28633.py (shaft axis +Z, gearbox face
 *     at z = 0, body toward -Z).
 */
