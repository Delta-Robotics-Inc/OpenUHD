/**
 * Rebuild every generated output for the 5-inch quadcopter (PB-791, PB-792):
 *
 *   npx tsx library/systems/quadcopter-5in/generate.ts
 *
 * generated/bom.{md,json}     bill of materials
 * generated/wiring.md         pad-to-pad wiring and assembly checklist
 * generated/betaflight-cli.txt Betaflight configuration
 * generated/checks.md         system design checks, nominal and fault scenarios
 */
import { mkdirSync, writeFileSync } from "fs";
import { join } from "path";
import { fileURLToPath } from "url";
import { bomMarkdown, buildBom } from "../../../scripts/bom.js";
import { checkSystem } from "../../../src/system/checks.js";
import { wiringChecklist, wiringMarkdown } from "../../../src/system/wiring.js";
import { SYSTEM, lookup } from "./index.js";
import { SCENARIOS } from "./scenarios.js";
import { betaflightCli, betaflightConfig } from "./betaflight.js";

const OUT = join(fileURLToPath(new URL(".", import.meta.url)), "generated");
mkdirSync(OUT, { recursive: true });

// BOM
const bom = buildBom(SYSTEM, lookup);
writeFileSync(join(OUT, "bom.json"), JSON.stringify(bom, null, 2) + "\n");
writeFileSync(join(OUT, "bom.md"), bomMarkdown(SYSTEM, bom));

// Wiring
writeFileSync(join(OUT, "wiring.md"), wiringMarkdown(SYSTEM.name, wiringChecklist(SYSTEM, lookup)));

// Betaflight
const bf = betaflightConfig(SYSTEM, lookup);
writeFileSync(join(OUT, "betaflight-cli.txt"), betaflightCli(SYSTEM, bf));

// Checks
const checks = [`# System checks — ${SYSTEM.name}`, "", "Generated by `generate.ts` from `checkSystem`. Do not edit by hand.", ""];
for (const s of SCENARIOS) {
  const diagnostics = checkSystem(s.system, s.lookup).diagnostics;
  checks.push(`## ${s.label} (\`${s.id}\`)`, "", s.description, "");
  for (const d of diagnostics) checks.push(`- **${d.severity}** · ${d.rule} — ${d.message}`);
  checks.push("");
}
writeFileSync(join(OUT, "checks.md"), checks.join("\n"));

console.log(`generated: bom (${bom.length} lines), wiring, betaflight-cli (${bf.lines.length} lines, ${bf.warnings.length} warnings), checks (${SCENARIOS.length} scenarios)`);
