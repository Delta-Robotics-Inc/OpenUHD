/**
 * Mounting hardware of the 5-inch quadcopter that is not yet a researched
 * library part (PB-775): generic ISO fasteners, standoffs and spacers, and
 * the screws that ship with the motors and the O4 camera.
 *
 * Dimensions are the nominal values of the named standards (ISO 4762 socket
 * head cap screws, ISO 10511 thin nyloc nuts); lengths are chosen from the
 * stack-ups in harnesses.ts, where each choice is argued. None of these is
 * audited, so every one carries an `assumption` trait naming what was
 * chosen, and included screws whose lengths the manufacturer does not state
 * carry a `data_gap`.
 *
 * Mass (PB-797): the Ettinger spacers and standoff use the weight on
 * Ettinger's per-article datasheet. Westfield's pages state no weight, so
 * screws and nuts declare a material and their mass is the generated CAD
 * volume × density, an assumption (see A2 below).
 */
import type { MaterialSpec, ModuleDef } from "../../../src/types/index.js";
import { connectorTrait, fastenerDiameterMm } from "../../../src/protocols/index.js";
import { cadArtifacts } from "../../cad/artifacts.js";

/**
 * Body artifacts generated by library/cad/py/hardware.py. The generator moved
 * out of UHD with the other tools (library/MOVED.md); the generated files stay,
 * and the source artifact keeps provenance only.
 */
const hardwareCad = (id: string) =>
  cadArtifacts({ dir: "library/systems/quadcopter-5in/artifacts/cad/hardware", name: id, generator: "library/cad/py/hardware.py", tool: "build123d 0.13.0" }).map((a) =>
    a.id === "cad_source" ? { ...a, filePath: undefined, description: "Generated by library/cad/py/hardware.py, which moved out of UHD with the other tools (library/MOVED.md)." } : a,
  );

/**
 * Materials for mass = CAD volume × density (PB-797) where no supplier
 * states a weight. The CAD bodies are hardware.py's nominal
 * shapes (ISO 4762 head with hex socket and a plain shank at 0.95 d; hex
 * nut with its bore), so every computed mass is an assumption.
 */
const A2: MaterialSpec = {
  name: "A2 (304 / 1.4301) stainless steel",
  density_g_cm3: 8.0,
  source: "https://www.thyssenkrupp-materials.co.uk/stainless-steel-304-14301.html",
  assumption: "Volume is the generator's nominal shape (plain shank, no thread form), not a measured part.",
};
const A2_UNSTATED: MaterialSpec = {
  ...A2,
  assumption: "The maker does not state the screw material; steel (A2 density) and the generator's nominal ISO 4762 shape are assumed.",
};
const A2_NYLOC: MaterialSpec = {
  ...A2,
  assumption: "Nominal hex nut shape with the nylon insert counted as steel (a slight over-estimate); not a measured part.",
};

/** A supplier listing that was fetched and checked (fastener research, 2026-09-26). */
interface Supplier {
  name: string;
  partNumber: string;
  url: string;
  title: string;
  packQuantity?: number;
  note?: string;
  /** Mass per piece as the supplier's datasheet states it (PB-797). */
  weight?: { g: number; source: string; quote: string };
}

const supplierTraits = (sup?: Supplier) =>
  sup
    ? [
        {
          type: "usage_note",
          params: { note: `Supplier listing: ${sup.title} (${sup.name} ${sup.partNumber}).${sup.note ? " " + sup.note : ""}`, source: sup.url },
        },
        ...(sup.packQuantity ? [{ type: "performance", params: { kind: "packaging", pack_quantity: sup.packQuantity, source: sup.url } }] : []),
      ]
    : [];

interface ScrewSpec {
  id: string;
  size: 2 | 3;
  length: number;
  name?: string;
  includedWith?: string;
  supplier?: Supplier;
  why: string;
}

const HEAD = { 2: { dk: 3.8, k: 2.0 }, 3: { dk: 5.5, k: 3.0 } } as const;

function screw(s: ScrewSpec): ModuleDef {
  const head = HEAD[s.size];
  return {
    id: s.id,
    name: s.name ?? `M${s.size} x ${s.length} mm socket head cap screw, ISO 4762`,
    kind: "module",
    manufacturer: s.includedWith ? "Included (unbranded)" : "Generic (ISO 4762 / DIN 912)",
    ...(s.supplier ? { part_number: s.supplier.partNumber } : {}),
    description: `ISO 4762 socket head cap screw M${s.size} x ${s.length} mm (head Ø${head.dk} x ${head.k} mm nominal). ${s.why}`,
    tags: ["standard-part", "fastener", "screw", `m${s.size}`, "iso-4762"],
    categories: ["hardware"],
    interfaces: [
      {
        id: "thread",
        name: `M${s.size} external thread, ${s.length} mm`,
        domain: "mechanical",
        exposed: true,
        default_active: true,
        protocols: [{ type: "custom", roles: ["peer"] }],
        capabilities: ["fastener", "external_thread"],
        parameters: [fastenerDiameterMm(s.size), { id: "length", unit: "mm", value: s.length }],
        traits: [connectorTrait("metric_thread_external", { gender: "male" })],
      },
    ],
    domains: [
      {
        domain: "mechanical",
        dimensions_mm: { length: s.length + head.k, width: head.dk, height: head.dk },
        material: s.includedWith ? A2_UNSTATED : A2,
        metadata: { head_diameter_mm: head.dk, head_height_mm: head.k, standard: "ISO 4762 (nominal)" },
      },
    ],
    traits: [
      { type: "assumption", params: { field: "length", value: `${s.length} mm`, reason: s.why } },
      ...supplierTraits(s.supplier),
      ...(s.includedWith
        ? [
            { type: "usage_note", params: { note: `Ships with ${s.includedWith}.`, included_with: s.includedWith } },
            { type: "data_gap", params: { fields: ["screw length"], note: "The manufacturer includes screws but does not state their length; the length here is chosen for the stack-up." } },
          ]
        : []),
    ],
    artifacts: hardwareCad(s.id),
  };
}

function hexPart(o: {
  id: string;
  name: string;
  kind: "nut" | "spacer" | "standoff";
  size: 2 | 3;
  length: number;
  od: number;
  threaded: boolean;
  material: string;
  supplier?: Supplier;
  /** Material for mass from CAD volume when the supplier states no weight. */
  massMaterial?: MaterialSpec;
  why: string;
}): ModuleDef {
  return {
    id: o.id,
    name: o.name,
    kind: "module",
    manufacturer: o.supplier?.name ?? "Generic",
    ...(o.supplier ? { part_number: o.supplier.partNumber } : {}),
    description: `${o.name}. ${o.why}`,
    tags: ["standard-part", "fastener", o.kind, `m${o.size}`],
    categories: ["hardware"],
    interfaces: [
      {
        id: o.kind === "nut" ? "thread" : "bore",
        name: o.threaded ? `M${o.size} internal thread` : `Ø${o.size + 0.4} mm bore`,
        domain: "mechanical",
        exposed: true,
        default_active: true,
        protocols: [{ type: "custom", roles: ["peer"] }],
        capabilities: o.threaded ? ["fastener", "internal_thread"] : ["fastener"],
        parameters: [fastenerDiameterMm(o.size), { id: "length", unit: "mm", value: o.length }],
        traits: [connectorTrait(o.threaded ? "metric_thread_internal" : "clearance_bore", { gender: "female" })],
      },
    ],
    domains: [
      {
        domain: "mechanical",
        dimensions_mm: { length: o.od, width: o.od, height: o.length },
        ...(o.supplier?.weight ? { weight_g: o.supplier.weight.g } : {}),
        ...(o.massMaterial && !o.supplier?.weight ? { material: o.massMaterial } : {}),
        metadata: { outer_mm: o.od, material: o.material, ...(o.supplier?.weight ? { source: o.supplier.weight.source, weight_quote: o.supplier.weight.quote } : {}) },
      },
    ],
    traits: [{ type: "assumption", params: { field: "part choice", value: o.name, reason: o.why } }, ...supplierTraits(o.supplier)],
    artifacts: hardwareCad(o.id),
  };
}

